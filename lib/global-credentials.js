import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { PLATFORMS } from './platforms.js'

const MARKER = '--yunzai-repo-manager-global'
const quote = value => `'${value.replaceAll("'", "'\\''")}'`
const exactPattern = value => `^${value.replace(/[\\^$.*+?()[\]{}|]/g, '\\$&')}$`

// Git values are never included in errors: another tool's helper may contain secrets.
function runGit (directory, args, missing = []) {
  try {
    return execFileSync('git', ['-C', directory, ...args], {
      encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 8000, windowsHide: true
    })
  } catch (error) {
    if (missing.includes(error.status) && !String(error.stderr || '').trim()) return ''
    const reason = error.code === 'ENOENT' ? '找不到 Git 可执行文件'
      : error.code === 'ETIMEDOUT' ? 'Git 配置操作超时'
        : '请检查 Git 配置格式、文件权限及是否存在配置锁文件'
    throw new Error(reason)
  }
}

function values (text) {
  return text ? text.split('\0').slice(0, -1) : []
}

// Accept only the exact shell form generated by this plugin, including old Node paths.
function shellWords (text) {
  const words = []
  let word = ''
  let quoted = false
  let started = false
  for (let index = 0; index < text.length; index++) {
    const char = text[index]
    if (char === "'") { quoted = !quoted; started = true }
    else if (!quoted && char === '\\') {
      if (++index === text.length) return []
      word += text[index]
      started = true
    } else if (!quoted && char === ' ') {
      if (started) { words.push(word); word = ''; started = false }
    } else { word += char; started = true }
  }
  if (quoted) return []
  if (started) words.push(word)
  return words
}

export function createGlobalCredentialManager ({ pluginRoot, botRoot, execute = runGit }) {
  const helperFile = path.join(pluginRoot, 'lib', 'git-credential.js').replaceAll('\\', '/')
  const node = process.execPath.replaceAll('\\', '/')
  const command = `!${quote(node)} ${quote(helperFile)} ${MARKER}`
  let lastError = ''

  function isOwnedHelper (value) {
    if (!value.startsWith('!')) return false
    const words = shellWords(value.slice(1))
    if (words.length !== 2 && !(words.length === 3 && words[2] === MARKER)) return false
    const [executable, script] = words
    if (!/^(?:\/|[A-Za-z]:\/)/.test(executable) || !/\/node(?:\.exe)?$/i.test(executable)) return false
    const equalPath = process.platform === 'win32'
      ? script.toLowerCase() === helperFile.toLowerCase() : script === helperFile
    return equalPath && value === `!${quote(executable)} ${quote(script)}${words.length === 3 ? ` ${MARKER}` : ''}`
  }

  function readHelpers (directory, scope, includes = false) {
    return values(execute(directory, ['config', ...(scope ? [scope] : []), ...(includes ? ['--includes'] : []),
      '--null', '--get-all', 'credential.helper'], [1]))
  }

  function remove (directory, scope, value) {
    execute(directory, ['config', scope, '--unset-all', 'credential.helper', exactPattern(value)], [5])
  }

  function add (directory, scope, value) {
    execute(directory, ['config', scope, '--add', 'credential.helper', value])
  }

  function repositories () {
    const result = []
    for (const rootName of ['plugins', 'user_plugins']) {
      const root = path.join(botRoot, rootName)
      if (!fs.existsSync(root)) continue
      for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
        if (!entry.isDirectory()) continue
        const directory = path.join(root, entry.name)
        if (fs.existsSync(path.join(directory, '.git'))) result.push({ directory, key: `${rootName}/${entry.name}` })
      }
    }
    return result
  }

  function sync (config) {
    const undo = []
    let cleaned = 0
    const rollback = () => {
      const failures = []
      for (const action of [...undo].reverse()) {
        try { action() } catch { failures.push('恢复失败') }
      }
      return failures.length === 0
    }
    try {
      const existing = readHelpers(botRoot, '--global')
      const own = existing.filter(isOwnedHelper)
      const enabled = PLATFORMS.some(({ id }) => config.credentials?.[id]?.username || config.credentials?.[id]?.password)
      if (!(enabled && own.length === 1 && own[0] === command)) {
        for (const value of new Set(own)) {
          remove(botRoot, '--global', value)
          undo.push(() => { for (const entry of own.filter(item => item === value)) add(botRoot, '--global', entry) })
        }
        if (enabled) {
          add(botRoot, '--global', command)
          undo.push(() => remove(botRoot, '--global', command))
        }
      }
      for (const repo of repositories()) {
        const local = readHelpers(repo.directory, '--local')
        for (const value of new Set(local.filter(isOwnedHelper))) {
          try { remove(repo.directory, '--local', value) } catch {
            throw new Error(`旧 helper 清理失败（${repo.key}），请检查该仓库的配置权限或锁文件`)
          }
          undo.push(() => { for (const entry of local.filter(item => item === value)) add(repo.directory, '--local', entry) })
          cleaned += local.filter(item => item === value).length
        }
      }
      lastError = ''
      return { enabled, cleaned, rollback }
    } catch (error) {
      const restored = rollback()
      lastError = `全局 Git 认证同步失败：${error.message}${restored ? '' : '；部分 helper 回滚失败，请检查 Git 配置'}`
      throw new Error(lastError)
    }
  }

  function status (config) {
    const configured = PLATFORMS.map(platform => {
      const credential = config.credentials?.[platform.id] || {}
      const state = credential.username && credential.password ? '已配置'
        : credential.username || credential.password ? '填写不完整，不提供凭据' : '未配置'
      return `${platform.label}（${platform.hosts.join('、')}）：${state}`
    })
    const warnings = []
    let registered = false
    try {
      const global = readHelpers(botRoot, '--global', true)
      registered = global.includes(command)
      // A normal read also sees inherited system helpers, without using --system.
      if (readHelpers(botRoot, null, true).some(value => !isOwnedHelper(value))) {
        warnings.push('保留了其他 Git 助手：按 Git 原有顺序调用，先返回完整凭据的助手优先生效。')
      }
      if (execute(botRoot, ['config', '--includes', '--null', '--get-regexp', '^credential\\..+\\.helper$'], [1])) {
        warnings.push('检测到用户的 URL 专用 helper；它可能改变对应地址的认证顺序，请检查该配置。')
      }
      const ownIndex = global.indexOf(command)
      if (ownIndex >= 0 && global.slice(ownIndex + 1).includes('')) {
        warnings.push('其他全局配置在本插件之后重置了助手列表，本插件可能不生效；请自行检查该配置。')
      }
      for (const repo of repositories()) {
        const local = readHelpers(repo.directory, '--local', true)
        if (local.some(isOwnedHelper)) warnings.push(`${repo.key}：仍有旧专用 helper，请重新保存配置以清理。`)
        if (local.includes('')) warnings.push(`${repo.key}：用户配置重置了本地助手列表，可能不使用全局凭据。`)
        if (execute(repo.directory, ['config', '--local', '--includes', '--null', '--get-regexp', '^credential\\..+\\.helper$'], [1])) {
          warnings.push(`${repo.key}：存在用户的 URL 专用本地 helper，可能覆盖全局认证。`)
        }
      }
    } catch (error) { warnings.push(`无法读取认证状态：${error.message}`) }
    if (lastError) warnings.push(lastError)
    return {
      registered,
      warnings,
      summary: [registered ? '全局助手已接入（当前运行 Yunzai 的系统用户）' : '全局助手未接入；填写账号后保存配置以同步',
        ...configured, ...warnings,
        '此状态只检查本地配置，不验证 Token 有效性；SSH 不使用这些凭据。'].join('\n')
    }
  }

  return { sync, status, command, isOwnedHelper }
}
